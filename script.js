const homePage = document.getElementById("home-page");
const wordPage = document.getElementById("word-page");
const imageGrid = document.getElementById("image-grid");
const wordTitle = document.getElementById("word-title");
const largeImage = document.getElementById("large-image");
const ipaButtons = document.getElementById("ipa-buttons");
const backButton = document.getElementById("back-button");

function buildHomePage() {
  imageGrid.innerHTML = "";

  words.forEach((item, index) => {
    const card = document.createElement("div");
    card.className = "image-card";

    card.innerHTML = `
      <img src="${item.image}" alt="${item.word}">
      <p>${item.word}</p>
    `;

    card.addEventListener("click", () => {
      openWordPage(index);
    });

    imageGrid.appendChild(card);
  });
}

function openWordPage(index) {
  const item = words[index];

  wordTitle.textContent = item.word;
  largeImage.src = item.image;
  largeImage.alt = item.word;

  ipaButtons.innerHTML = "";

  item.productions.forEach((production) => {
    const button = document.createElement("button");
    button.className = "ipa-button";
    button.textContent = production.ipa;

    button.addEventListener("click", () => {
  playAudio(production.audio, button);
  });

    ipaButtons.appendChild(button);
  });

  homePage.classList.remove("active");
  wordPage.classList.add("active");
}

function playAudio(audioPath) {
  const audio = new Audio(audioPath);
  audio.play();
}
function playAudio(audioPath, button) {
  const audio = new Audio(audioPath);

  button.classList.add("playing");

  audio.play();

  audio.addEventListener("ended", () => {
    button.classList.remove("playing");
  });
}

backButton.addEventListener("click", () => {
  wordPage.classList.remove("active");
  homePage.classList.add("active");
});

buildHomePage();
